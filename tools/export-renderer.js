// Copies the compiled WiflyGlyphs + WiflyNameRenderer runtime bytecode (contracts/out, from `forge build`) into the backend,
// so name previews use the exact onchain renderer code. Re-run after changing the renderer:
//   cd contracts && forge build && cd .. && node tools/export-renderer.js
const fs = require('fs')
const path = require('path')
const root = path.resolve(__dirname, '..')
const read = p => JSON.parse(fs.readFileSync(path.join(root, 'contracts/out', p), 'utf8'))
const g = read('WiflyGlyphs.sol/WiflyGlyphs.json'), r = read('WiflyNameRenderer.sol/WiflyNameRenderer.json')
const out = {
  note: 'runtime bytecode from contracts/src/render (forge build). generated by tools/export-renderer.js',
  glyphs: g.deployedBytecode.object,
  renderer: r.deployedBytecode.object,
  rendererImmutables: Object.values(r.deployedBytecode.immutableReferences || {}).flat(),
  abi: r.abi.filter(x => x.name === 'svg' || x.name === 'tokenURI'),
}
fs.writeFileSync(path.join(root, 'backend/src/names-art/renderer.json'), JSON.stringify(out))
console.log('renderer bytes', out.renderer.length / 2 - 1, 'glyph bytes', out.glyphs.length / 2 - 1)
